import {chromium} from '@playwright/test';
import fs from 'node:fs/promises';
const browser=await chromium.launch({channel:'chrome',headless:true});
const page=await browser.newPage({viewport:{width:1440,height:1000}});
const errors=[];page.on('pageerror',e=>errors.push(e.message));
await page.goto('http://127.0.0.1:8765');
await page.locator('input[type=file]').setInputFiles({name:'brief.txt',mimeType:'text/plain',buffer:Buffer.from('附件验证：画幅 9:16。只用于文件保留和项目隔离验收，不请求制作。','utf8')});
await page.locator('.attachment-list').getByText('brief.txt',{exact:true}).waitFor();
await page.getByLabel('消息',{exact:true}).fill('附件留存验收：请调用 get_project 确认 brief.txt 附件属于本项目，只回复已收到，不修改规划，不请求制作。');
await page.getByRole('button',{name:'发送',exact:true}).click();
await page.waitForURL(/\/projects\/[a-f0-9]+/);const pid=page.url().split('/').pop();
await page.getByRole('link',{name:'brief.txt',exact:true}).waitFor();
await page.reload();await page.getByRole('link',{name:'brief.txt',exact:true}).waitFor();
const snapshot=await page.request.get(`http://127.0.0.1:8765/api/projects/${pid}`).then(r=>r.json());
if(snapshot.messages.filter(m=>m.role==='user').length!==1)throw Error('First message duplicated');
await page.getByRole('button',{name:'清晨花店',exact:true}).click();
await page.waitForURL(/49b2b8b68b1a46ab99d232d6992e1a52/);
await page.locator('.topbar').getByText('清晨花店',{exact:true}).waitFor();
if(await page.getByRole('link',{name:'brief.txt',exact:true}).count())throw Error('Files leaked between projects');
await fs.writeFile('docs/evidence/attachment-verification.json',JSON.stringify({project:pid,firstMessagePreserved:true,filePreserved:true,projectSwitchIsolated:true,errors},null,2));
await browser.close();console.log(JSON.stringify({passed:true,errors}));
