import {chromium} from '@playwright/test';
import fs from 'node:fs/promises';
const record=JSON.parse(await fs.readFile('docs/evidence/browser-project.json','utf8'));
const browser=await chromium.launch({channel:'chrome',headless:true});
const page=await browser.newPage({viewport:{width:1440,height:1000}});
const errors=[];page.on('pageerror',e=>errors.push(e.message));
await page.goto(record.url);
await page.getByRole('button',{name:/制作任务/}).click();
await page.getByRole('button',{name:'生成配套交付',exact:true}).click();
await page.getByRole('heading',{name:'交付版本',exact:true}).waitFor();
await page.locator('.delivery video').waitFor();
await page.locator('.delivery video').evaluate(async v=>{v.muted=true;await v.play()});
await page.waitForFunction(()=>document.querySelector('.delivery video')?.currentTime>0.2);
await page.screenshot({path:'docs/evidence/browser-delivery.png',fullPage:true});
const snapshot=await page.request.get(`http://127.0.0.1:8765/api/projects/${record.project}`).then(r=>r.json());
await fs.writeFile('docs/evidence/real-delivery.json',JSON.stringify({project:record.project,revision:snapshot.revision,tasks:snapshot.tasks,deliveries:snapshot.deliveries,usage:snapshot.usage,browserErrors:errors,validation:'Real Ark generation, actual preview playback, paired native draft export. Jianying editor UI not verified.'},null,2));
await page.getByRole('button',{name:'素材',exact:true}).click();
await page.getByRole('button',{name:'备份至 COS（预留 ¥1）',exact:true}).first().click();
await page.getByRole('button',{name:'COS 已校验',exact:true}).waitFor({timeout:60000});
await page.screenshot({path:'docs/evidence/browser-assets-cos.png',fullPage:true});
await browser.close();console.log(JSON.stringify({previewPlayed:true,cosVerified:true,errors}));
